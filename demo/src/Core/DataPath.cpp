//------------------------------------------------------------------------------
std::vector<std::string> DataPath::pathes() const
{
    std::vector<std::string> res;
    res.reserve(m_search_paths.size());
    for (auto const& it: m_search_paths)
    {
        res.push_back(it);
    }

    return res;
}

//------------------------------------------------------------------------------
std::string DataPath::toString() const
{
    std::string string_path;

    for (auto const& it: m_search_paths)
    {
        if (!string_path.empty())
        {
            string_path += m_delimiter;
        }
        string_path += it;
    }

    return string_path;
}

//------------------------------------------------------------------------------
void DataPath::split(std::string const& path, bool front)
{
    std::stringstream ss(path);
    std::string directory;
    // Splitting produces the directories in order; inserting them one by one at
    // the front would reverse them, hence the intermediate list.
    std::list<std::string> directories;

    while (std::getline(ss, directory, m_delimiter))
    {
        if (directory.empty())
            continue ;

        if ((*directory.rbegin() == '\\') || (*directory.rbegin() == '/'))
            directories.push_back(directory);
        else
            directories.push_back(directory + "/");
    }

    if (front)
    {
        m_search_paths.splice(m_search_paths.begin(), directories);
    }
    else
    {
        m_search_paths.splice(m_search_paths.end(), directories);
    }
}
